fn normalize_symbol(value: String) -> Result<String, DecisionRecordValidationError> {
    let normalized = value.trim().to_owned();
    if normalized.is_empty()
        || normalized.len() > MAX_SYMBOL_LEN
        || !normalized.is_ascii()
        || normalized.chars().any(char::is_control)
    {
        return Err(DecisionRecordValidationError::InvalidSymbol);
    }

    Ok(normalized.to_ascii_uppercase())
}

fn normalize_currency(value: String) -> Result<String, DecisionRecordValidationError> {
    let normalized = value.trim().to_ascii_uppercase();
    if normalized.len() == 3
        && normalized
            .chars()
            .all(|character| character.is_ascii_uppercase())
    {
        Ok(normalized)
    } else {
        Err(DecisionRecordValidationError::InvalidCurrency)
    }
}

fn normalize_decimal_string(value: String) -> Result<String, DecisionRecordValidationError> {
    let normalized = value.trim();
    if normalized.is_empty()
        || normalized
            .parse::<Decimal>()
            .map_or(true, |value| value <= Decimal::ZERO)
    {
        Err(DecisionRecordValidationError::InvalidDecimalString)
    } else {
        Ok(normalized.to_owned())
    }
}

fn validate_snapshot(
    value: &Value,
    field: &'static str,
) -> Result<(), DecisionRecordValidationError> {
    if value.is_null() {
        Err(DecisionRecordValidationError::InvalidSnapshot { field })
    } else {
        Ok(())
    }
}

fn normalize_summary(value: String) -> Result<String, DecisionRecordValidationError> {
    let normalized = value.trim().to_owned();
    if normalized.is_empty() || normalized.len() > MAX_SUMMARY_LEN {
        Err(DecisionRecordValidationError::InvalidSummary)
    } else {
        Ok(normalized)
    }
}

fn normalize_manual_execution_note(
    value: String,
) -> Result<String, ManualExecutionValidationError> {
    let normalized = value.trim().to_owned();
    if normalized.is_empty() || normalized.len() > MAX_MANUAL_EXECUTION_NOTE_LEN {
        Err(ManualExecutionValidationError::InvalidNote)
    } else {
        Ok(normalized)
    }
}

