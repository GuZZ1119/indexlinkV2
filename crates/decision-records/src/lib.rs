/// Execution status captured by a decision record.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum DecisionExecutionStatus {
    /// The plan is active and the preview date matches the schedule.
    Due,
    /// The plan is active but the preview date is not the schedule date.
    Waiting,
    /// The plan is inactive and should not execute.
    Inactive,
}

/// 生成一条决策记录的策略版本与通用推荐快照。
///
/// 该结构仅保存策略身份和已确定的推荐输出；70/20/10 或其他策略专属证据仍保留在
/// 各自的输入快照列中。旧记录可为 `None`，以保持迁移前审计历史可读。
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct DecisionPolicyEvidence {
    /// 生成推荐的不可变策略版本。
    pub policy: PolicyRef,
    /// 不包含凭据的通用推荐快照。
    pub recommendation_snapshot: Value,
}

